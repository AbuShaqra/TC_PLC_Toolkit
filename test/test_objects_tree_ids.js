/**
 * @file test_objects_tree_ids.js
 * @description Pins every Objects-tree element the provider renders on the committed sample, as
 * VS Code sees it: id, label, contextValue, collapsible state, icon, tooltip, click command and
 * getParent() answer, plus the element and ancestor ids getRevealItem() produces for every file and
 * component.
 *
 * VS Code keys expansion state, selection and `TreeView.reveal()` on the tree item id. If a refactor
 * changes one id, a user's expanded tree collapses after the update and a reveal can stop on the wrong
 * node, and no other headless gate notices. So the snapshot in
 * `test/fixtures/objects-tree-ids.json` was recorded from the provider as it stood before the R4
 * objects-tree model refactor, and this harness fails if any recorded field changes.
 *
 * It also checks two things directly, so a snapshot regenerated by mistake cannot hide them:
 *  - getParent(child) returns the id of the element whose getChildren() listed it, and getParent of a
 *    root returns nothing. VS Code walks this chain on every reveal.
 *  - the element getRevealItem() returns for a file or component has the same id, and the same ancestor
 *    ids, as that element in the expanded tree.
 *
 * Six tree shapes are covered: one solution (the first sample, copied alone into a temp root so its
 * ids keep their `<ROOT>/TcToolkitSample/…` form), two solutions (the two-project fixture), two PLC
 * projects without a solution (grouped roots), one PLC project without a solution, the flat tree (no
 * project map), and the committed `sample/` itself — two solutions of different layouts (3.1.4026's
 * `.tsproj` and 3.1.4024's `.tspproj`, `TcToolkitSample2/`).
 *
 * This harness drives the VS Code-facing adapter (src/treeDataProvider.js), so it needs a `vscode`
 * stub. The stub is backed by the real filesystem. The model itself is tested without one in
 * test_objects_tree_model.js.
 *
 * Regenerate (only for a deliberate, reviewed id change): node test/test_objects_tree_ids.js --write
 */

const Module = require('module');
const fs = require('fs');
const path = require('path');
const { reportCoverage } = require('./_coverage');
const os = require('os');
const { sampleAvailable, buildTwoProjectFixture, SAMPLE_PROJECT } = require('./_multiproject');

const SNAPSHOT = path.join(__dirname, 'fixtures', 'objects-tree-ids.json');
const WRITE = process.argv.includes('--write');
const SAMPLE_ROOT = path.join(__dirname, '..', 'sample');

if (!sampleAvailable()) {
    console.log('sample/ project not present — skipping the Objects-tree id pin.');
    reportCoverage('objects-tree-ids', 'skipped', 'sample/ project not present');
    process.exit(0);
}

// ── vscode stub, backed by the real filesystem ──────────────────────────────────────────────────
const uriFor = (fsPath) => ({
    scheme: 'file',
    fsPath,
    toString: () => 'file:///' + fsPath.replace(/\\/g, '/').replace(/^\/+/, '')
});
const FileType = { File: 1, Directory: 2, SymbolicLink: 64 };
let workspaceFolders = [];

const ModuleResolve = Module._resolveFilename;
Module._resolveFilename = function (req, ...rest) {
    if (req === 'vscode') return 'vscode-objects-tree-ids-stub';
    return ModuleResolve.call(this, req, ...rest);
};
require.cache['vscode-objects-tree-ids-stub'] = {
    id: 'vscode-objects-tree-ids-stub', filename: 'vscode-objects-tree-ids-stub', loaded: true,
    exports: {
        EventEmitter: class { constructor() { this.event = () => {}; } fire() {} },
        TreeItem: class { constructor(label, state) { this.label = label; this.collapsibleState = state; } },
        TreeItemCollapsibleState: { None: 0, Collapsed: 1, Expanded: 2 },
        ThemeIcon: class { constructor(id, color) { this.id = id; this.color = color; } },
        ThemeColor: class { constructor(id) { this.id = id; } },
        FileType,
        Uri: { file: uriFor, joinPath: (base, name) => uriFor(path.join(base.fsPath, name)) },
        workspace: {
            get workspaceFolders() { return workspaceFolders; },
            fs: {
                readDirectory: async (uri) => fs.readdirSync(uri.fsPath, { withFileTypes: true })
                    .map(e => [e.name, e.isDirectory() ? FileType.Directory : (e.isFile() ? FileType.File : 0)]),
                readFile: async (uri) => fs.readFileSync(uri.fsPath)
            },
            openTextDocument: async (uri) => {
                const text = fs.readFileSync(uri.fsPath, 'utf8');
                return { getText: () => text };
            }
        }
    }
};

const { TwinCatTreeDataProvider } = require('../src/treeDataProvider');
const { createProjectMap } = require('../src/lsp/projectMap');
const { createSolutionMap } = require('../src/solutionMap');

let errors = 0;
function assert(cond, msg) {
    if (cond) return;
    console.error(`[FAIL] ${msg}`);
    errors++;
}

/**
 * Walks the whole tree the way VS Code would expand it, and records each element.
 * @param {string} root Workspace root path; its uri prefix is replaced with `<ROOT>` so the
 *   snapshot does not depend on where the repo or the temp fixture lives.
 * @param {Object|null} projectMap
 * @param {Object|null} solutionMap
 * @returns {Promise<{nodes: Array<Object>, reveals: Array<Object>}>}
 */
async function capture(root, projectMap, solutionMap) {
    workspaceFolders = [{ uri: uriFor(root) }];
    const rootKey = uriFor(root).toString();
    const rel = (s) => (typeof s === 'string' ? s.split(rootKey).join('<ROOT>') : s);
    const provider = new TwinCatTreeDataProvider(() => projectMap, () => solutionMap);

    const nodes = [];
    const ancestry = new Map(); // id → ancestor ids, nearest first
    const labels = new Map(); // id → label shown by getChildren
    const revealTargets = [];

    const visit = async (element, parentId, ancestors, depth) => {
        const item = provider.getTreeItem(element);
        const id = item.id;
        const parent = provider.getParent(element);
        const reportedParent = parent ? provider.getTreeItem(parent).id : null;
        assert(reportedParent === parentId,
            `getParent(${rel(id)}) is the element that listed it (expected ${rel(parentId)}, got ${rel(reportedParent)})`);
        const icon = item.iconPath
            ? { id: item.iconPath.id, color: item.iconPath.color ? item.iconPath.color.id : null }
            : null;
        const command = item.command
            ? { command: item.command.command, args: [rel(item.command.arguments[0].toString()), item.command.arguments[1]] }
            : null;
        nodes.push({
            depth,
            id: rel(id),
            label: item.label,
            contextValue: item.contextValue,
            collapsibleState: item.collapsibleState,
            icon,
            tooltip: item.tooltip === undefined ? null : rel(item.tooltip),
            command,
            parent: rel(reportedParent)
        });
        ancestry.set(id, ancestors);
        labels.set(id, item.label);
        if (command) revealTargets.push({ uri: item.command.arguments[0], componentId: item.command.arguments[1], id });
        if (item.collapsibleState === 0) return;
        const children = await provider.getChildren(element);
        for (const child of children) await visit(child, id, [id, ...ancestors], depth + 1);
    };
    for (const rootElement of await provider.getChildren(undefined)) await visit(rootElement, null, [], 0);

    // Every clickable row (file or component) must reveal as the same id with the same ancestry.
    const reveals = [];
    for (const target of revealTargets) {
        const element = await provider.getRevealItem(target.uri, target.componentId);
        const id = provider.getTreeItem(element).id;
        const chain = [];
        const chainLabels = [];
        for (let p = provider.getParent(element); p; p = provider.getParent(p)) {
            const parentItem = provider.getTreeItem(p);
            chain.push(parentItem.id);
            chainLabels.push(parentItem.label);
            if (chain.length > 32) break;
        }
        assert(id === target.id, `getRevealItem(${rel(target.uri.toString())}, ${target.componentId}) is the tree's element (expected ${rel(target.id)}, got ${rel(id)})`);
        assert(JSON.stringify(chain) === JSON.stringify(ancestry.get(target.id)),
            `reveal ancestry of ${rel(target.id)} matches the tree (expected ${rel(JSON.stringify(ancestry.get(target.id)))}, got ${rel(JSON.stringify(chain))})`);
        // Same id is what VS Code matches on, but the label is what a user reads in a reveal
        // ancestor (and what test/devhost asserts): it must be the label getChildren shows.
        const treeLabels = (ancestry.get(target.id) || []).map(a => labels.get(a));
        assert(JSON.stringify(chainLabels) === JSON.stringify(treeLabels),
            `reveal ancestor labels of ${rel(target.id)} match the tree (expected ${JSON.stringify(treeLabels)}, got ${JSON.stringify(chainLabels)})`);
        reveals.push({ target: rel(target.id), id: rel(id), ancestors: chain.map(rel) });
    }
    return { nodes, reveals };
}

(async () => {
    const fixture = buildTwoProjectFixture();
    // The first sample alone under a root of its own: sample/ now holds a second solution, and these
    // single-solution shapes pin the first sample's ids exactly as they were recorded.
    const oneRoot = fs.mkdtempSync(path.join(os.tmpdir(), 'tc_tree_ids_'));
    fs.cpSync(SAMPLE_PROJECT, path.join(oneRoot, path.basename(SAMPLE_PROJECT)), { recursive: true });
    const captured = {};
    try {
        const sampleProjects = createProjectMap([oneRoot]);
        captured['one-solution'] = await capture(oneRoot, sampleProjects, createSolutionMap([oneRoot], sampleProjects));

        const twoProjects = createProjectMap([fixture.root]);
        captured['two-solutions'] = await capture(fixture.root, twoProjects, createSolutionMap([fixture.root], twoProjects));
        captured['two-projects-grouped'] = await capture(fixture.root, twoProjects, null);
        // One project and no solution: the solution map exists but is empty, so the tree stays flat.
        captured['one-project-no-solution'] = await capture(oneRoot, sampleProjects,
            { solutions: [], orphanProjects: [], solutionForProject: () => null });
        captured['flat'] = await capture(oneRoot, null, null);
        // The committed sample/ as a workspace: two solutions, one per template layout.
        const bothProjects = createProjectMap([SAMPLE_ROOT]);
        captured['two-sample-solutions'] = await capture(SAMPLE_ROOT, bothProjects, createSolutionMap([SAMPLE_ROOT], bothProjects));
    } finally {
        fixture.cleanup();
        fs.rmSync(oneRoot, { recursive: true, force: true });
    }

    for (const [name, shot] of Object.entries(captured)) {
        assert(shot.nodes.length > 0, `${name}: the tree has elements`);
        assert(shot.reveals.length > 0, `${name}: the tree has reveal targets`);
        const ids = shot.nodes.map(n => n.id);
        assert(new Set(ids).size === ids.length, `${name}: every tree id is unique`);
    }

    if (WRITE) {
        fs.mkdirSync(path.dirname(SNAPSHOT), { recursive: true });
        // One element per line: a reviewable diff when an id ever changes on purpose.
        const lines = Object.entries(captured).map(([name, shot]) => ` ${JSON.stringify(name)}: {\n` +
            ['nodes', 'reveals'].map(part => `  ${JSON.stringify(part)}: [\n` +
                shot[part].map(e => '   ' + JSON.stringify(e)).join(',\n') + '\n  ]').join(',\n') + '\n }');
        fs.writeFileSync(SNAPSHOT, '{\n' + lines.join(',\n') + '\n}\n');
        console.log(`Wrote ${SNAPSHOT}`);
    } else {
        const expected = JSON.parse(fs.readFileSync(SNAPSHOT, 'utf8'));
        for (const name of Object.keys(expected)) {
            const want = expected[name];
            const got = captured[name];
            assert(!!got, `${name}: scenario captured`);
            if (!got) continue;
            for (const part of ['nodes', 'reveals']) {
                assert(got[part].length === want[part].length,
                    `${name}: ${part} count unchanged (expected ${want[part].length}, got ${got[part].length})`);
                const n = Math.max(got[part].length, want[part].length);
                let reported = 0;
                for (let i = 0; i < n && reported < 10; i++) {
                    const a = JSON.stringify(want[part][i]);
                    const b = JSON.stringify(got[part][i]);
                    if (a !== b) {
                        reported++;
                        assert(false, `${name}: ${part}[${i}] changed\n  expected ${a}\n  got      ${b}`);
                    }
                }
            }
        }
        const total = Object.values(expected).reduce((sum, s) => sum + s.nodes.length, 0);
        if (!errors) console.log(`[PASS] ${total} tree elements and their reveal chains match the pinned snapshot across ${Object.keys(expected).length} tree shapes`);
    }

    reportCoverage('objects-tree-ids', 'ran');
    if (errors) {
        console.error(`\n${errors} Objects-tree id assertion(s) failed.`);
        process.exit(1);
    }
    console.log('\nAll Objects-tree id assertions passed.');
})().catch(err => {
    console.error('[FAIL] harness crashed: ' + (err && err.stack ? err.stack : err));
    process.exit(1);
});
